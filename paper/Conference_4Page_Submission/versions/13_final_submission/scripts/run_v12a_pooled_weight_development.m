function value = parse_logical(raw)
if iscell(raw)
    assert(isscalar(raw),'Expected one logical CSV value.');
    raw = raw{1};
end
if islogical(raw)
    assert(isscalar(raw),'Expected one logical value.');
    value = raw;
elseif isnumeric(raw)
    assert(isscalar(raw) && isfinite(raw) && any(raw==[0 1]), ...
        'Expected a finite 0/1 logical value.');
    value = logical(raw);
else
    token = lower(strtrim(string(raw)));
    assert(isscalar(token),'Expected one textual logical value.');
    if any(token==["true","1","yes"])
        value = true;
    elseif any(token==["false","0","no"])
        value = false;
    else
        error('run_v12a_pooled_weight_development:InvalidLogical', ...
            'Could not parse logical field: %s',token);
    end
end
end

