timestamps=double(envelope.timestamps_s(:));
controls=double(envelope.controls);
assert(size(trajectory,1)==row.PathStateCount && ...
    size(trajectory,1)==row.Steps+1 && numel(timestamps)==size(trajectory,1) && ...
    size(controls,1)==size(trajectory,1) && ...
    all(isfinite(trajectory),'all') && all(isfinite(timestamps)) && ...
    all(isfinite(controls),'all') && ...
    all(abs(timestamps(:)-(0:row.Steps)'*double(cfg.dt))<=1e-10) && ...
    norm(trajectory(1,1:3)'-double(scenario.start(:)))<=1e-10 && ...
