function row = summarize_supplemental_result(res,scenario,candidateIndex, ...
    candidateKey,methodKey,methodLabel,sceneIndex,scenarioSeed, ...
    samplingSeed,goalTolerance,maxSteps,uavRadius,retryCount,retryReasons)
required = {'traj','time','ctrl','finalDist','success','collisions','pathLength', ...
    'meanStepTime','steps','failureType','emergencyInfeasibleSteps', ...
    'fallbackSteps','solveFailures'};
assert(all(isfield(res,required)), ...
    'Simulator output lacks required route/metric fields.');
traj = double(res.traj);
assert(ismatrix(traj) && size(traj,1)>=1 && size(traj,2)>=3 && ...
    all(isfinite(traj(:))), ...
    'Simulator returned a missing or nonfinite trajectory.');
assert(norm(traj(1,1:3)'-scenario.start(:))<=1e-10, ...
    'Trajectory initial position differs from the fixed scene start.');
finalDistance = norm(traj(end,1:3)'-scenario.goal(:));
reportedDistance = double(res.finalDist);
assert(isscalar(reportedDistance) && isfinite(reportedDistance) && ...
    close_enough(reportedDistance,finalDistance), ...
    'Simulator finalDist is missing, nonfinite, or inconsistent with trajectory.');
pathLength = double(res.pathLength);
legacyStepInclusiveTime = double(res.meanStepTime)*1000;
assert(isscalar(pathLength) && isfinite(pathLength) && pathLength>=0 && ...
    isscalar(legacyStepInclusiveTime) && ...
    (isnan(legacyStepInclusiveTime) || ...
    (isfinite(legacyStepInclusiveTime) && legacyStepInclusiveTime>=0)), ...
    'Simulator returned missing/nonfinite path length or invalid legacy timing.');
steps = double(res.steps);
assert(isscalar(steps) && isfinite(steps) && steps>=0 && ...
    steps==floor(steps) && size(traj,1)==steps+1, ...
    'Simulator step count does not match recorded trajectory states.');
assert(~isnan(legacyStepInclusiveTime) || steps==0, ...
    'Legacy per-step time is unavailable despite executed simulation steps.');
assert(isscalar(res.success) && isfinite(double(res.success)) && ...
    isscalar(res.collisions) && isfinite(double(res.collisions)) && ...
    isscalar(res.emergencyInfeasibleSteps) && ...
    isfinite(double(res.emergencyInfeasibleSteps)) && ...
    isscalar(res.fallbackSteps) && isfinite(double(res.fallbackSteps)) && ...
    isscalar(res.solveFailures) && isfinite(double(res.solveFailures)), ...
    'Simulator returned an invalid completion status.');
failureType = string(res.failureType);
assert(isscalar(failureType) && strlength(failureType)>0, ...
    'Simulator returned no failure/terminal classification.');
[nativeCollision,~,correctedCollision,~,minGap] = ...
    audit_swept_path_leq(traj,scenario.obstacles,uavRadius);
nativeGoal = finalDistance<goalTolerance;
correctedGoal = finalDistance<=goalTolerance;
originalSafe = nativeGoal && ~nativeCollision;
% All true simulator failures with a finite trajectory remain ordinary
% non-arrivals when they miss tolerance; no exception is classified here.
steps = double(res.steps);
terminalReason = supplemental_terminal_reason(finalDistance,goalTolerance, ...
    steps,maxSteps,double(res.emergencyInfeasibleSteps));
row = make_episode_row(candidateIndex,candidateKey,methodKey,methodLabel, ...
    sceneIndex,scenarioSeed,samplingSeed,goalTolerance,finalDistance,minGap, ...
    originalSafe,nativeCollision,logical(res.success),pathLength, ...
    legacyStepInclusiveTime,failureType,terminalReason,steps,size(traj,1), ...
    retryCount,retryReasons);
assert(row.NativeGoalArrival==nativeGoal && ...
    row.CorrectedGoalArrival==correctedGoal && ...
    row.CorrectedSweptCollision==correctedCollision, ...
    'Internal raw/corrected classification mismatch.');
end

function reason = supplemental_terminal_reason(finalDistance,goalTolerance, ...
    steps,maxSteps,emergencyInfeasibleSteps)
if finalDistance<=goalTolerance
    reason = "goal_reached";
elseif steps>=maxSteps
    reason = "max_steps";
elseif emergencyInfeasibleSteps>0
    reason = "infeasible_emergency_stop";
else
    reason = "other_early_termination";
end
end

