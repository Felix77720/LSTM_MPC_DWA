required={'trajectory','timestamps_s','controls','obstacleTracks', ...
    'start_m','goal_m','terminalState','terminalReason','failureType', ...
    'routeDataSHA256'};
assert(all(isfield(envelope,required)), ...
    'A completed episode checkpoint lacks a full route/provenance payload.');
