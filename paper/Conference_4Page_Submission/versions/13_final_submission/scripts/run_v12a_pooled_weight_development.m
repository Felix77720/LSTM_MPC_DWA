function value = file_sha256(path)
md = java.security.MessageDigest.getInstance('SHA-256');
fid = fopen(path,'r');
assert(fid>=0,'Could not open file for SHA-256: %s',path);
cleanup = onCleanup(@() fclose(fid));
bytes = fread(fid,Inf,'*uint8');
md.update(bytes);
digest = typecast(md.digest(),'uint8');
value = lower(reshape(dec2hex(digest)',1,[]));
end

function value = directory_sha256(folder)
files = dir(fullfile(folder,'**','*'));
files = files(~[files.isdir]);
assert(~isempty(files),'Dependency folder contains no files: %s',folder);
fullPaths = strings(numel(files),1);
for i = 1:numel(files)
    fullPaths(i) = string(fullfile(files(i).folder,files(i).name));
end
[~,order] = sort(fullPaths);
files = files(order);
parts = strings(numel(files),1);
for i = 1:numel(files)
    fullPath = fullfile(files(i).folder,files(i).name);
    relativePath = extractAfter(string(fullPath),strlength(string(folder))+1);
    parts(i) = relativePath+":"+string(file_sha256(fullPath));
end
value = sha256_text(char(strjoin(parts,'|')));
end

