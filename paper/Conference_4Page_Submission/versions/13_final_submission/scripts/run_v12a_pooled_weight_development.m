assert(strcmpi(char(envelope.routeDataSHA256),expectedSHA), ...
    'Full trajectory/timestamp/control/obstacle-track hash does not reproduce.');
end

function value=episode_data_sha256(trajectory,timestamps,controls,obstacles)
md=java.security.MessageDigest.getInstance('SHA-256');
md.update(typecast(double(trajectory(:)),'uint8'));
md.update(typecast(double(timestamps(:)),'uint8'));
md.update(typecast(double(controls(:)),'uint8'));
for j=1:numel(obstacles)
    md.update(typecast(double(obstacles(j).traj(:)),'uint8'));
    md.update(typecast(double(obstacles(j).radius),'uint8'));
end
digest=typecast(md.digest(),'uint8');
value=lower(reshape(dec2hex(digest)',1,[]));
end

function [nativeCollision,nativeEvents,correctedCollision, ...
    correctedEvents,minGap] = audit_swept_path_leq(traj,obstacles,uavRadius)
assert(isfinite(uavRadius) && uavRadius>=0, ...
    'Invalid UAV radius for swept path audit.');
assert(~isempty(obstacles),'Fixed development scene has no obstacles.');
nativeCollision = false;
correctedCollision = false;
nativeEvents = 0;
correctedEvents = 0;
minGap = inf;
previousNative = false;
previousCorrected = false;
nIntervals = max(1,size(traj,1)-1);
for k = 1:nIntervals
    intervalNative = false;
    intervalCorrected = false;
    if size(traj,1)==1, kRight=1; else, kRight=k+1; end
    for j = 1:numel(obstacles)
        obstacleTraj = double(obstacles(j).traj);
        assert(size(obstacleTraj,1)>=kRight && size(obstacleTraj,2)>=3 && ...
            all(isfinite(obstacleTraj(k:kRight,1:3)),'all'), ...
            'Obstacle trajectory is too short/nonfinite for swept audit.');
        relStart = traj(k,1:3)'-obstacleTraj(k,1:3)';
        relEnd = traj(kRight,1:3)'-obstacleTraj(kRight,1:3)';
        delta = relEnd-relStart;
        den = dot(delta,delta);
        if den>0
            alpha = max(0,min(1,-dot(relStart,delta)/den));
        else
            alpha = 0;
        end
        gap = norm(relStart+alpha*delta)-double(obstacles(j).radius)-uavRadius;
        assert(isfinite(gap),'Nonfinite swept clearance encountered.');
        minGap = min(minGap,gap);
        intervalNative = intervalNative || gap<0;
        intervalCorrected = intervalCorrected || gap<=0;
    end
    nativeCollision = nativeCollision || intervalNative;
    correctedCollision = correctedCollision || intervalCorrected;
    nativeEvents = nativeEvents+double(intervalNative && ~previousNative);
    correctedEvents = correctedEvents+double(intervalCorrected && ~previousCorrected);
    previousNative = intervalNative;
    previousCorrected = intervalCorrected;
end
assert(isfinite(minGap),'Swept minimum clearance could not be computed.');
end

