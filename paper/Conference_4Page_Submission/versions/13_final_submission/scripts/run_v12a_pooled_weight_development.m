function outdir = run_v12a_pooled_weight_development(preflightOnly,workerPreflightOnly)
%RUN_V12A_POOLED_WEIGHT_DEVELOPMENT Pool trust-weight selection across five arms.
% Pass true to validate/hash all frozen inputs without starting simulations.
% Pass false,true to create a fresh local pool, verify every worker path, and
% return before any episode is launched or output directory is created.
% This is an isolated development runner using a fresh, path-verified local
% four-worker pool. It uses the fixed 48-scene source and frozen candidate
% grid/model metadata, and freshly simulates all five integrated arms for
% every candidate, scene, and sampling seed. No historical trajectory result
% is reused or reclassified.
%
% Scoring rule (frozen in this file): for each candidate, calculate mean
% corrected safe arrival across the three seeds within each scene, then mean
% across scenes within each method, then the unweighted mean across the five
% methods. Ties within 1e-12 are broken by fewer corrected contacts across
% all five arms, greater mean swept clearance (equal method/scene weighting),
% then the original candidate order.
%
% Simulator exceptions or invalid required outputs are persisted as keyed
% failure records and stop this run before any selection is written. Resume
% reuses only complete records with identical source/code hashes; failed jobs
% retain their retry history. Existing pools are never reused or modified.

if nargin==1 && (ischar(preflightOnly) || ...
        (isstring(preflightOnly) && isscalar(preflightOnly))) && ...
        string(preflightOnly)=="__endpoint-selftest__"
    scriptDir=fileparts([mfilename('fullpath') '.m']);
    outdir=endpoint_rule_selftest(scriptDir);
    fprintf('Inclusive endpoint/contact synthetic test passed; no simulation or outcomes read.\n');
    return;
end

if nargin<1 || isempty(preflightOnly), preflightOnly=false; end
if nargin<2 || isempty(workerPreflightOnly), workerPreflightOnly=false; end
assert(isscalar(preflightOnly) && (islogical(preflightOnly) || ...
    (isnumeric(preflightOnly) && any(preflightOnly==[0 1]))), ...
    'preflightOnly must be a logical scalar.');
preflightOnly=logical(preflightOnly);
assert(isscalar(workerPreflightOnly) && (islogical(workerPreflightOnly) || ...
    (isnumeric(workerPreflightOnly) && any(workerPreflightOnly==[0 1]))), ...
    'workerPreflightOnly must be a logical scalar.');
workerPreflightOnly=logical(workerPreflightOnly);
assert(~(preflightOnly && workerPreflightOnly), ...
    'Choose either data preflight or worker preflight, not both.');
scriptPath = [mfilename('fullpath') '.m'];
scriptDir = fileparts(scriptPath);
revisionDir = fileparts(scriptDir);
projectRoot = fileparts(fileparts(fileparts(fileparts(revisionDir))));
resultsRoot = fullfile(projectRoot,'results');

baseline = fullfile(projectRoot,'MPC_DWA_Fusion');
assert(isfolder(baseline),'MPC_DWA_Fusion baseline folder is missing: %s',baseline);
casadiPath = fullfile(baseline,'third_party', ...
    'casadi-3.8.0-windows64-matlab2018b');
assert(isfolder(casadiPath), 'Required CasADi folder is missing: %s',casadiPath);
addpath(projectRoot,baseline,casadiPath);

sourceDir = fullfile(resultsRoot,'confirmatory_revision', ...
    'confirmatory_48scenes_20261005_050804');
sourceBundlePath = fullfile(sourceDir,'experiment_bundle.mat');
sourceRawPath = fullfile(sourceDir,'confirmatory_raw.csv');
sourceManifestPath = fullfile(sourceDir,'scenario_manifest.csv');
tuneDir = fullfile(resultsRoot,'v12_trust_weight_tuning_dev48_20261006');
tuneBundlePath = fullfile(tuneDir,'tuning_bundle.mat');
% The source tune bundle records the unmodified v12 parent protocol SHA. The
% v13 copy adds a supersession notice, so hash it separately rather than
% pretending it is the exact source named by the tune bundle.
protocolPath = fullfile(projectRoot,'paper','Conference_4Page_Submission', ...
    'versions','12_redesigned_submission','04_review', ...
    'redesigned_comparison_protocol.md');
protocolOverlayPath = fullfile(revisionDir,'04_review', ...
    'redesigned_comparison_protocol.md');
pooledProtocolPath = fullfile(revisionDir,'04_review', ...
    'pooled_weight_selection_protocol_v12a.md');
amendmentPath = fullfile(revisionDir,'04_review', ...
    'protocol_amendment_endpoint_inclusive_20261012.md');
requiredInputs = {sourceBundlePath,sourceRawPath,sourceManifestPath, ...
    tuneBundlePath,protocolPath,protocolOverlayPath, ...
    pooledProtocolPath,amendmentPath};
for i = 1:numel(requiredInputs)
    assert(isfile(requiredInputs{i}), ...
        'Required frozen input is missing: %s',requiredInputs{i});
end

sourceBundleSHA = file_sha256(sourceBundlePath);
sourceRawSHA = file_sha256(sourceRawPath);
sourceManifestSHA = file_sha256(sourceManifestPath);
tuneBundleSHA = file_sha256(tuneBundlePath);
protocolSHA = file_sha256(protocolPath);
protocolOverlaySHA = file_sha256(protocolOverlayPath);
pooledProtocolSHA = file_sha256(pooledProtocolPath);
amendmentSHA = file_sha256(amendmentPath);
pooledProtocolText = fileread(pooledProtocolPath);
assert(contains(pooledProtocolText,'Status: frozen before pooled calibration'), ...
    ['The v12a pooled-calibration protocol must be frozen before execution; ' ...
     'the amendment is still proposed or has not been explicitly frozen.']);
amendmentText=fileread(amendmentPath);
assert(exact_frozen_status(amendmentText) && ...
    contains(amendmentText,'Rerun all 4,320 episodes') && ...
    contains(amendmentText,'distance <= goal tolerance') && ...
    contains(amendmentText,'clearance <= 0') && ...
    contains(amendmentText,'prediction and DWA screening horizon is 3 s'), ...
    'Endpoint-inclusive full-rerun amendment is not frozen or lacks required rules.');

tuneMeta = load(tuneBundlePath,'sourceSHA','modelPath','modelSHA', ...
    'protocolSHA','codeSHA','candidateKeys','candidateWeights','candidateLabels');
assert(strcmpi(char(tuneMeta.sourceSHA),sourceBundleSHA), ...
    'The original tune bundle points to a different 48-scene source bundle.');
assert(strcmpi(char(tuneMeta.protocolSHA),protocolSHA), ...
    'The original tune bundle was generated under a different protocol hash.');

source = load(sourceBundlePath,'cfg','scenarios','seeds','scenarioSeed','modelSHA');
assert(numel(source.scenarios)==48 && isequal(double(source.seeds(:)'),1:3) && ...
    double(source.scenarioSeed)==20261006, ...
    'Unexpected fixed 48-scene development bundle.');
sourceConfigSHA256 = sha256_text(jsonencode(source.cfg));
assert(strcmpi(char(source.modelSHA),char(tuneMeta.modelSHA)), ...
    'The fixed scene bundle and tune records reference different models.');

candidateKeys = string(tuneMeta.candidateKeys(:)');
candidateLabels = string(tuneMeta.candidateLabels(:)');
candidateWeights = double(tuneMeta.candidateWeights);
assert(numel(candidateKeys)==6 && numel(unique(candidateKeys))==6 && ...
    isequal(size(candidateWeights),[6,4]) && ...
    numel(candidateLabels)==6 && all(isfinite(candidateWeights),'all') && ...
    all(candidateWeights>=0,'all') && ...
    all(abs(sum(candidateWeights,2)-1)<1e-12), ...
    'The original tune bundle does not contain the expected six valid candidates.');
expectedCandidateKeys = ["equal","safety","goal","tracking", ...
    "smoothness","existing_engineering"];
expectedCandidateWeights = [0.25 0.25 0.25 0.25; ...
    0.55 0.15 0.15 0.15; ...
    0.15 0.55 0.15 0.15; ...
    0.15 0.15 0.55 0.15; ...
    0.15 0.15 0.15 0.55; ...
    0.35 0.30 0.15 0.20];
assert(isequal(candidateKeys,expectedCandidateKeys) && ...
    isequal(candidateWeights,expectedCandidateWeights), ...
    'Candidate keys/weights differ from the predeclared finite grid.');

modelPath = char(tuneMeta.modelPath);
assert(isfile(modelPath),'The model path in the original tune bundle is missing: %s',modelPath);
modelSHA = file_sha256(modelPath);
assert(strcmpi(modelSHA,char(tuneMeta.modelSHA)), ...
    'The model file differs from the hash recorded in the original tune bundle.');
modelData = load(modelPath,'net','muX','sigX','muY','sigY');
assert(all(isfield(modelData,{'net','muX','sigX','muY','sigY'})), ...
    'The archived model is missing required network or normalization fields.');

cfg = source.cfg;
cfg.dyn.muX = modelData.muX;
cfg.dyn.sigX = modelData.sigX;
cfg.dyn.muY = modelData.muY;
cfg.dyn.sigY = modelData.sigY;
cfg.predictTime = 3.0;
cfg.mpc.N = 30;
cfg.dyn.N_pred = 30;
cfg.dyn.injectHorizon = 30;
cfg.dyn.dt = cfg.dt;
goalTolerance = double(cfg.goalTolerance);
assert(isscalar(goalTolerance) && isfinite(goalTolerance) && goalTolerance>0, ...
    'The source bundle has an invalid goal tolerance.');

methodKeys = ["lstm","cv","lstm_mpc_cv_dwa", ...
    "cv_mpc_lstm_dwa","static"];
methodLabels = ["MPC-DWA (shared LSTM)","Coupled MPC-DWA (CV)", ...
    "MPC-DWA (LSTM to MPC only)","MPC-DWA (LSTM to DWA only)", ...
    "Reconstructed MPC-DWA (latest-position hold in both layers)"];
sceneCount = numel(source.scenarios);
seedValues = double(source.seeds(:)');
maxSteps = double(source.cfg.maxSteps);
expectedFreshEpisodes = numel(candidateKeys)* ...
    numel(methodKeys)*sceneCount*numel(seedValues);
assert(expectedFreshEpisodes==4320 && numel(methodKeys)==5 && ...
    sceneCount==48 && isequal(seedValues,1:3), ...
    'Unexpected complete pooled calibration plan; expected 4,320 fresh episodes.');

if preflightOnly
    fprintf('Pooled-development input preflight passed; no simulations started.\n');
    fprintf('Validated six frozen weight vectors, 48 scenes, 3 seeds, and 5 integrated arms; no outcomes loaded.\n');
    return;
end

assert(license('test','Distrib_Computing_Toolbox') && exist('parpool','file')==2, ...
    'The frozen four-worker pooled calibration requires Parallel Computing Toolbox.');
assert(isempty(gcp('nocreate')), ...
    'Start this runner from a clean MATLAB session with no active parallel pool.');
workerCount = 4;
pool = parpool('local',workerCount);
poolCleanup = onCleanup(@() close_pool_if_valid(pool));
workerPathAudit = verify_worker_paths(scriptDir,projectRoot,baseline,casadiPath);
workerPathAuditSHA = worker_path_audit_sha256(workerPathAudit);
if workerPreflightOnly
    fprintf('Four-worker path preflight passed; no simulation episodes started.\n');
    fprintf('Worker path audit SHA-256: %s\n',workerPathAuditSHA);
    return;
end

effectiveBaseConfigSHA256 = sha256_text(jsonencode(cfg));
configFilePath = fullfile(projectRoot,'config_LSTM.m');
configFileSHA256 = file_sha256(configFilePath);
[runtimeDependencyInventory,runtimeDependencyInventorySHA256] = ...
    runtime_dependency_inventory(scriptDir,projectRoot,baseline,casadiPath);

dataSHA = sha256_text(strjoin({sourceBundleSHA,sourceRawSHA, ...
    sourceManifestSHA,tuneBundleSHA,protocolSHA,protocolOverlaySHA, ...
    pooledProtocolSHA,amendmentSHA},'|'));
simulatorPath = fullfile(scriptDir,'simulate_dynamic_v12a_timed.m');
assert(isfile(simulatorPath),'Frozen timed integrated simulator is missing.');
simulatorSHA = file_sha256(simulatorPath);
supplementalRunnerSHA = file_sha256(scriptPath);
provenance = struct( ...
    'OriginalRunnerPath',string(simulatorPath), ...
    'OriginalRunnerSHA256',string(simulatorSHA), ...
    'SupplementalRunnerPath',string(scriptPath), ...
    'SupplementalRunnerSHA256',string(supplementalRunnerSHA), ...
    'OriginalCodeSHA256',string(runtimeDependencyInventorySHA256), ...
    'RuntimeDependencyInventory',string(runtimeDependencyInventory), ...
    'RuntimeDependencyInventorySHA256',string(runtimeDependencyInventorySHA256), ...
    'SimulatorSHA256',string(simulatorSHA), ...
    'TrustFunctionSHA256',string(file_sha256(fullfile(projectRoot,'computeTrust_dynamic.m'))), ...
    'StandaloneSimulatorSHA256',string(file_sha256(fullfile(scriptDir,'simulate_standalone_controller_v12a_timed.m'))), ...
    ... Preserve the legacy field/value while giving its meaning and active configs explicit names.
    'ConfigSHA256',string(configFileSHA256), ...
    'ConfigFilePath',string(configFilePath), ...
    'ConfigFileSHA256',string(configFileSHA256), ...
    'ConfigSHA256Meaning', ...
        "Legacy compatibility alias for ConfigFileSHA256; active settings use the source/effective config hashes.", ...
    'LoadedSourceConfigSHA256',string(sourceConfigSHA256), ...
    'EffectiveBaseConfigSHA256',string(effectiveBaseConfigSHA256), ...
    'ModelPath',string(modelPath),'ModelSHA256',string(modelSHA), ...
    'SourceBundlePath',string(sourceBundlePath), ...
    'SourceBundleSHA256',string(sourceBundleSHA), ...
    'SourceRawCSVPath',string(sourceRawPath), ...
    'SourceRawCSV_SHA256',string(sourceRawSHA), ...
    'ScenarioManifestPath',string(sourceManifestPath), ...
    'ScenarioManifestSHA256',string(sourceManifestSHA), ...
    'OriginalTuneBundlePath',string(tuneBundlePath), ...
    'OriginalTuneBundleSHA256',string(tuneBundleSHA), ...
    'ProtocolPath',string(protocolPath),'ProtocolSHA256',string(protocolSHA), ...
    'ProtocolOverlayPath',string(protocolOverlayPath), ...
    'ProtocolOverlaySHA256',string(protocolOverlaySHA), ...
    'PooledProtocolPath',string(pooledProtocolPath), ...
    'PooledProtocolSHA256',string(pooledProtocolSHA), ...
    'AmendmentPath',string(amendmentPath), ...
    'AmendmentSHA256',string(amendmentSHA), ...
    'MatlabVersion',string(version), ...
    'MatlabRelease',string(version('-release')), ...
    'ComputerArchitecture',string(computer), ...
    'WorkerCount',double(workerCount), ...
    'WorkerPathAuditSHA256',string(workerPathAuditSHA), ...
    'CasadiFolder',string(casadiPath), ...
    'CasadiTreeSHA256',string(directory_sha256(casadiPath)), ...
    'CombinedInputDataSHA256',string(dataSHA));
provenanceSignature = provenance_signature(provenance,candidateKeys, ...
    candidateLabels,candidateWeights,methodKeys,goalTolerance,seedValues);

% New execution directory preserves the first interrupted attempt and its error.
outdir = fullfile(resultsRoot, ...
    'v12a_pooled_weight_development_inclusive_dev48_20261012');
episodesDir = fullfile(outdir,'episodes');
errorsDir = fullfile(outdir,'errors');
manifestPath = fullfile(outdir,'pooled_development_manifest.mat');
lockDir = fullfile(outdir,'.pooled_development_lock');
if ~isfolder(outdir), mkdir(outdir); end
lockFile = java.io.File(lockDir);
assert(lockFile.mkdir(), ...
    'Could not acquire exclusive runner lock; inspect stale/concurrent lock: %s',lockDir);
lockCleanup = onCleanup(@() release_runner_lock(lockDir));

manifest = struct('provenance',provenance, ...
    'provenanceSignature',string(provenanceSignature), ...
    'status',"running",'startedUTC',string(datetime('now','TimeZone','UTC', ...
        'Format','yyyy-MM-dd''T''HH:mm:ssXXX')), ...
    'candidateKeys',candidateKeys,'candidateLabels',candidateLabels, ...
    'candidateWeights',candidateWeights,'methodKeys',methodKeys, ...
    'methodLabels',methodLabels,'sceneCount',sceneCount, ...
    'scenarioSeed',double(source.scenarioSeed),'samplingSeeds',seedValues, ...
    'goalTolerance_m',goalTolerance, ...
    'expectedOriginalSharedRecords',0, ...
    'expectedOriginalSharedEpisodeMATs',0, ...
    'expectedSupplementalEpisodes',expectedFreshEpisodes, ...
    'expectedFreshEpisodes',expectedFreshEpisodes, ...
    'fullRerunNoHistoricalEpisodeReuse',true, ...
    'expectedPooledRows',4320, ...
    'primaryScoreRule', ...
    "mean_method(mean_scene(mean_seed(corrected_safe_goal_arrival)))", ...
    'correctedContactRule','SweptMinClearance_m <= 0', ...
    'correctedGoalRule','FinalDistance_m <= GoalTolerance_m', ...
    'tieBreakRule', ...
    'min pooled corrected collision runs; max equal-method mean swept clearance; original candidate order', ...
    'executionMode','fresh local four-worker pool; worker paths verified', ...
    'workerCount',workerCount,'workerPathAudit',workerPathAudit, ...
    'workerPathAuditSHA256',workerPathAuditSHA);

if isfile(manifestPath)
    saved = load(manifestPath,'manifest');
    assert(isfield(saved,'manifest') && ...
        strcmp(string(saved.manifest.provenanceSignature),string(provenanceSignature)), ...
        'Existing pooled-development output has different provenance; refusing resume.');
else
    existing = dir(outdir);
    existingNames = string({existing.name});
    existingNames = existingNames(~ismember(existingNames,[".","..", ...
        ".pooled_development_lock"]));
    assert(isempty(existingNames), ...
        'Output directory has files but no manifest; refusing unsafe resume: %s',outdir);
    if ~isfolder(episodesDir), mkdir(episodesDir); end
    if ~isfolder(errorsDir), mkdir(errorsDir); end
    save_mat_atomic(manifestPath,struct('manifest',manifest));
