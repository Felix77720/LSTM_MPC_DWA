netConstant = parallel.pool.Constant(modelData.net);
candidateKeyConstant = parallel.pool.Constant(candidateKeys);
candidateWeightConstant = parallel.pool.Constant(candidateWeights);
methodKeyConstant = parallel.pool.Constant(methodKeys);
methodLabelConstant = parallel.pool.Constant(methodLabels);
seedConstant = parallel.pool.Constant(seedValues);
constantCleanup = onCleanup(@() delete_parallel_constants( ...
    scenarioConstant,cfgConstant,netConstant,candidateKeyConstant, ...
    candidateWeightConstant,methodKeyConstant,methodLabelConstant,seedConstant));
nMethods = numel(methodKeys);
nSeeds = numel(seedValues);
jobsPerCandidate = sceneCount*nSeeds*nMethods;
parfor jobIndex = 1:expectedFreshEpisodes
    ci = floor((jobIndex-1)/jobsPerCandidate)+1;
    withinCandidate = mod(jobIndex-1,jobsPerCandidate);
    si = floor(withinCandidate/(nSeeds*nMethods))+1;
    withinScene = mod(withinCandidate,nSeeds*nMethods);
    seedIndex = floor(withinScene/nMethods)+1;
    mi = mod(withinScene,nMethods)+1;
    seed = seedConstant.Value(seedIndex);
    scenario = scenarioConstant.Value(si);
    key = methodKeyConstant.Value(mi);
    label = methodLabelConstant.Value(mi);
    jobKey = make_job_key(ci,key,si,double(scenario.scenarioSeed),seed);
    jobPath = fullfile(episodesDir,[char(jobKey) '.mat']);
    additionalRows(jobIndex,1) = run_supplemental_job(jobKey,jobPath,errorsDir, ...
        ci,candidateKeyConstant.Value(ci),candidateWeightConstant.Value(ci,:), ...
        key,label,si, ...
        double(scenario.scenarioSeed),seed,scenario,cfgConstant.Value,netConstant.Value, ...
        goalTolerance,maxSteps,provenance,provenanceSignature);
    if mod(jobIndex,100)==0 || jobIndex==expectedFreshEpisodes
        fprintf('Pooled development episode records validated: %d/%d\n', ...
            jobIndex,expectedFreshEpisodes);
    end
end

