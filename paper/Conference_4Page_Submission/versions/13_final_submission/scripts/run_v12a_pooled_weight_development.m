function paths = resolve_worker_dependency_paths(dependencyNames)
paths = cell(1,numel(dependencyNames));
for i = 1:numel(dependencyNames)
    dependencyName = string(dependencyNames{i});
    if startsWith(dependencyName,"local::")
        fields = split(dependencyName,"::");
        parentName = char(fields(2));
        localName = char(fields(3));
        parentPath = which(parentName);
        if isempty(parentPath)
            paths{i} = '';
            continue;
        end
        sourceText = fileread(parentPath);
        sourceLines=regexp(sourceText,'\r\n|\n|\r','split');
        localFound=false;
        for lineIndex=1:numel(sourceLines)
            declaration=strtrim(sourceLines{lineIndex});
            if ~startsWith(declaration,'function'), continue; end
            firstParen=strfind(declaration,'(');
            if isempty(firstParen), continue; end
            identifiers=regexp(declaration(1:firstParen(1)-1), ...
                '[A-Za-z][A-Za-z0-9_]*','match');
            if ~isempty(identifiers) && strcmp(identifiers{end},localName)
                localFound=true;
                break;
            end
        end
        if ~localFound
            paths{i} = '';
        else
            paths{i} = [parentPath '|local|' localName];
        end
    else
        paths{i} = which(char(dependencyName));
    end
end
end

