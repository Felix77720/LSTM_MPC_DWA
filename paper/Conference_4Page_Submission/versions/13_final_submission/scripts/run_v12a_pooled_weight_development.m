assert(numel(additionalRows)==expectedFreshEpisodes, ...
    'Fresh in-memory row count is incomplete.');
episodeFiles = episodeFiles(:);
[~,episodeOrder] = sort(string({episodeFiles.name}));
episodeFiles = episodeFiles(episodeOrder);
verifiedRows = repmat(empty_episode_row(),expectedFreshEpisodes,1);
episodeFileNames = strings(expectedFreshEpisodes,1);
episodeFileSHA256 = strings(expectedFreshEpisodes,1);
episodeRouteSHA256 = strings(expectedFreshEpisodes,1);
for ei = 1:expectedFreshEpisodes
    episodePath = fullfile(episodesDir,episodeFiles(ei).name);
    saved = load(episodePath,'jobEnvelope');
    assert(isfield(saved,'jobEnvelope') && ...
        string(saved.jobEnvelope.status)=="complete" && ...
        string(saved.jobEnvelope.provenanceSignature)==string(provenanceSignature), ...
        'Pooled episode is incomplete or has a different provenance: %s',episodePath);
    envelope = saved.jobEnvelope;
    row = envelope.row;
    validate_episode_row(row,row.CandidateIndex,row.CandidateKey,row.MethodKey, ...
        row.SceneIndex,row.ScenarioSeed,row.SamplingSeed,goalTolerance);
    assert(row.SceneIndex>=1 && row.SceneIndex<=sceneCount && ...
        row.CandidateIndex>=1 && row.CandidateIndex<=numel(candidateKeys) && ...
        any(methodKeys==string(row.MethodKey)) && ...
        any(seedValues==row.SamplingSeed) && ...
        double(row.ScenarioSeed)==double(source.scenarios(row.SceneIndex).scenarioSeed) && ...
        string(envelope.jobKey)==make_job_key(row.CandidateIndex,row.MethodKey, ...
            row.SceneIndex,row.ScenarioSeed,row.SamplingSeed) && ...
        strcmpi(episodeFiles(ei).name,[char(envelope.jobKey) '.mat']), ...
        'Episode filename/key does not match its complete row: %s',episodePath);
    validate_full_episode_payload(envelope,row,source.scenarios(row.SceneIndex),cfg);
    verifiedRows(ei,1)=row;
    episodeFileNames(ei)=string(episodeFiles(ei).name);
    episodeFileSHA256(ei)=string(file_sha256(episodePath));
    episodeRouteSHA256(ei)=string(envelope.routeDataSHA256);
end
pooledTable = struct2table(verifiedRows);
pooledTable = sortrows(pooledTable, ...
    {'CandidateIndex','MethodKey','SceneIndex','SamplingSeed'});
validate_pooled_coverage(pooledTable,candidateKeys,methodKeys, ...
    sceneCount,seedValues);
manifest.status="complete";
manifest.completedUTC=string(datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd''T''HH:mm:ssXXX'));
manifest.episodeRecordCount=expectedFreshEpisodes;
manifest.unresolvedFailureCount=0;
manifest.episodeInventory=table(episodeFileNames,episodeFileSHA256, ...
    episodeRouteSHA256,'VariableNames', ...
    {'FileName','MAT_SHA256','RouteData_SHA256'});
manifest.episodeInventorySHA256=sha256_text(strjoin( ...
    episodeFileNames+":"+episodeFileSHA256+":"+episodeRouteSHA256,"|"));
save_mat_atomic(manifestPath,struct('manifest',manifest));
write_table_atomic(manifest.episodeInventory,fullfile(outdir, ...
    'pooled_episode_sha256.csv'));
manifestSHA256=file_sha256(manifestPath);

[methodSummary,candidateSummary,selection,classificationAudit] = score_candidates( ...
    pooledTable,candidateKeys,candidateLabels,candidateWeights, ...
    methodKeys,sceneCount,seedValues);
selection.provenanceSignature = string(provenanceSignature);
selection.provenance = provenance;
selection.goalTolerance_m = goalTolerance;
selection.episodeInventorySHA256=manifest.episodeInventorySHA256;
selection.manifestSHA256=string(manifestSHA256);
selection.scoringRule = manifest.primaryScoreRule;
selection.tieBreakRule = manifest.tieBreakRule;
selection.endpointReclassification = classificationAudit;

write_table_atomic(pooledTable,fullfile(outdir,'pooled_development_raw.csv'));
write_table_atomic(methodSummary,fullfile(outdir, ...
    'pooled_candidate_method_scores.csv'));
write_table_atomic(candidateSummary,fullfile(outdir, ...
    'pooled_candidate_scores.csv'));
write_table_atomic(classificationAudit,fullfile(outdir, ...
    'pooled_endpoint_reclassification.csv'));
save_mat_atomic(fullfile(outdir,'pooled_weight_selection.mat'), ...
    struct('selection',selection,'methodSummary',methodSummary, ...
    'candidateSummary',candidateSummary, ...
    'classificationAudit',classificationAudit,'provenance',provenance, ...
    'candidateWeights',candidateWeights,'candidateKeys',candidateKeys));
save_mat_atomic(fullfile(outdir,'pooled_development_bundle.mat'), ...
    struct('pooledTable',pooledTable,'methodSummary',methodSummary, ...
    'candidateSummary',candidateSummary, ...
    'classificationAudit',classificationAudit,'selection',selection, ...
    'provenance',provenance,'manifest',manifest, ...
    'candidateWeights',candidateWeights,'candidateKeys',candidateKeys, ...
    'methodKeys',methodKeys,'methodLabels',methodLabels));
write_text_atomic(string(manifestSHA256)+"  pooled_development_manifest.mat"+newline, ...
    fullfile(outdir,'pooled_development_manifest.sha256'));
episodeInventoryPath=fullfile(outdir,'pooled_episode_sha256.csv');
write_text_atomic(string(file_sha256(episodeInventoryPath))+ ...
    "  pooled_episode_sha256.csv"+newline, ...
    fullfile(outdir,'pooled_episode_sha256.csv.sha256'));
artifactNames=["pooled_development_manifest.mat"; ...
    "pooled_development_raw.csv";"pooled_candidate_method_scores.csv"; ...
    "pooled_candidate_scores.csv";"pooled_endpoint_reclassification.csv"; ...
    "pooled_episode_sha256.csv";"pooled_weight_selection.mat"; ...
    "pooled_development_bundle.mat"];
artifactHashes=strings(numel(artifactNames),1);
for ai=1:numel(artifactNames)
    artifactHashes(ai)=string(file_sha256(fullfile(outdir,artifactNames(ai))));
end
write_table_atomic(table(artifactNames,artifactHashes, ...
    'VariableNames',{'FileName','SHA256'}), ...
    fullfile(outdir,'pooled_calibration_artifact_sha256.csv'));

fprintf('Pooled development complete: %s\n',outdir);
fprintf('Selected %s: score %.6f; corrected pooled collisions %d; clearance %.6f m\n', ...
    char(selection.CandidateKey),selection.PooledSafeGoalArrivalScore, ...
    selection.PooledSweptCollisionRuns,selection.PooledMeanSweptClearance_m);
end

function report=endpoint_rule_selftest(scriptDir)
integrated=fileread(fullfile(scriptDir,'simulate_dynamic_v12a_timed.m'));
standalone=fileread(fullfile(scriptDir,'simulate_standalone_controller_v12a_timed.m'));
assert(contains(integrated,'dist_to_goal <= cfg.goalTolerance') && ...
    contains(integrated,'res.finalDist <= cfg.goalTolerance') && ...
    contains(integrated,'if finalDist > goalTol') && ...
    contains(standalone,'state(1:3)-goal) <= cfg.goalTolerance') && ...
    contains(standalone,'finalDistance <= cfg.goalTolerance && collisions == 0') && ...
    contains(standalone,'finalDistance <= cfg.goalTolerance && ~piecewiseSweptCollision') && ...
    contains(standalone,'if finalDist > goalTol'), ...
    'Timed simulator stop/success/failure predicates are not consistently inclusive.');
goalTolerance=0.5;
goalDistances=[goalTolerance-1e-9,goalTolerance,goalTolerance+1e-9];
assert(isequal(goalDistances<=goalTolerance,[true true false]), ...
    'Synthetic inclusive goal-boundary fixture failed.');
sweptClearances=[-1e-9,0,1e-9];
assert(isequal(sweptClearances<=0,[true true false]), ...
    'Synthetic swept-contact boundary fixture failed.');
report=struct('GoalTolerance_m',goalTolerance, ...
    'GoalBoundaryArrival',logical(goalDistances<=goalTolerance), ...
    'SweptContactBoundary',logical(sweptClearances<=0), ...
    'NoSimulationStarted',true,'NoHistoricalOutcomesRead',true);
end

function frozen=exact_frozen_status(text)
matches=regexp(char(text), ...
    '(?m)^[ \t]*(?:\*\*)?Status:[ \t]*([^\r\n]*)$', ...
    'tokens');
if numel(matches)~=1
    frozen=false;
    return;
end
status=string(regexprep(strtrim(matches{1}{1}),'\*\*[ \t]*$',''));
frozen=(status=="frozen");
end

function row = run_supplemental_job(jobKey,jobPath,errorsDir, ...
    candidateIndex,candidateKey,candidateWeights,methodKey,methodLabel, ...
    sceneIndex,scenarioSeed,samplingSeed,scenario,cfg,net,goalTolerance, ...
    maxSteps,provenance,provenanceSignature)
retryHistory = empty_retry_history();
if isfile(jobPath)
    saved = load(jobPath,'jobEnvelope');
    assert(isfield(saved,'jobEnvelope'), ...
        'Existing job MAT lacks an envelope; refusing resume: %s',jobPath);
    old = saved.jobEnvelope;
    assert(string(old.jobKey)==string(jobKey) && ...
        string(old.provenanceSignature)==string(provenanceSignature), ...
        'Existing job key/provenance mismatch; refusing resume: %s',jobPath);
    retryHistory = old.retryHistory;
    if string(old.status)=="complete"
        row = old.row;
        validate_episode_row(row,candidateIndex,candidateKey,methodKey, ...
            sceneIndex,scenarioSeed,samplingSeed,goalTolerance);
        validate_full_episode_payload(old,row,scenario,cfg);
        return;
    end
    assert(string(old.status)=="failed", ...
        'Unrecognized existing job status in %s.',jobPath);
end

try
    cfgJob = cfg;
    cfgJob.coupling.sigma = candidateWeights;
    % Match the frozen common-random-number seed across candidate/method arms.
    rng(samplingSeed*100000+sceneIndex,'twister');
    res = simulate_dynamic_v12a_timed(scenario,char(methodKey),net,cfgJob);
    row = summarize_supplemental_result(res,scenario,candidateIndex, ...
        candidateKey,methodKey,methodLabel,sceneIndex,scenarioSeed, ...
        samplingSeed,goalTolerance,maxSteps,cfgJob.UAV_radius, ...
        numel(retryHistory), ...
        retry_history_text(retryHistory));
    validate_episode_row(row,candidateIndex,candidateKey,methodKey, ...
        sceneIndex,scenarioSeed,samplingSeed,goalTolerance);
    trajectory = double(res.traj);
    timestamps = double(res.time(:));
    controls = double(res.ctrl);
    assert(size(trajectory,1)==row.PathStateCount && ...
        size(trajectory,1)==numel(timestamps) && ...
        size(controls,1)==size(trajectory,1) && ...
        all(isfinite(trajectory),'all') && all(isfinite(timestamps)) && ...
        all(isfinite(controls),'all') && ...
        all(abs(timestamps(:)-(0:row.Steps)'*double(cfgJob.dt))<=1e-10), ...
        'Full route, control, and timestamp arrays are missing or misaligned.');
    routeSHA = episode_data_sha256(trajectory,timestamps,controls,scenario.obstacles);
    jobEnvelope = struct('jobKey',string(jobKey),'status',"complete", ...
        'provenanceSignature',string(provenanceSignature), ...
        'provenance',provenance,'retryHistory',retryHistory,'row',row, ...
        'trajectory',trajectory,'timestamps_s',timestamps,'controls',controls, ...
        'obstacleTracks',scenario.obstacles,'start_m',double(scenario.start(:)), ...
        'goal_m',double(scenario.goal(:)), ...
        'terminalState',trajectory(end,:),'terminalReason',row.TerminalReason, ...
        'failureType',row.FailureType,'routeDataSHA256',routeSHA);
    save_mat_atomic(jobPath,struct('jobEnvelope',jobEnvelope));
catch ME
    failure = struct('Attempt',numel(retryHistory)+1, ...
        'TimestampLocal',string(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
        'Identifier',string(ME.identifier),'Message',string(ME.message), ...
        'Stack',string(strjoin(arrayfun(@(x) ...
            sprintf('%s:%d',x.name,x.line),ME.stack,'UniformOutput',false),' | ')));
    retryHistory(end+1,1) = failure;
    jobEnvelope = struct('jobKey',string(jobKey),'status',"failed", ...
        'provenanceSignature',string(provenanceSignature), ...
        'provenance',provenance,'retryHistory',retryHistory, ...
        'row',struct());
    save_mat_atomic(jobPath,struct('jobEnvelope',jobEnvelope));
    append_failure_log(errorsDir,jobKey,failure);
    error('run_v12a_pooled_weight_development:EpisodeFailed', ...
        'Episode %s failed validation/simulation; no selection will be written. See %s.\n%s', ...
        char(jobKey),fullfile(errorsDir,[char(jobKey) '.txt']),ME.message);
end
end

