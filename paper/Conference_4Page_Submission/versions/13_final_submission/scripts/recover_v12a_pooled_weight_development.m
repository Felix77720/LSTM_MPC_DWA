function outdir = recover_v12a_pooled_weight_development()
%RECOVER_V12A_POOLED_WEIGHT_DEVELOPMENT Aggregate validated existing episodes.
% This entry point only loads, validates, and aggregates the frozen archive.
% All dependency, manifest, key, status, signature, and content-hash checks
% finish before a pool is created or an output is written.

scriptPath = [mfilename('fullpath') '.m'];
scriptDir = fileparts(scriptPath);
revisionDir = fileparts(scriptDir);
projectRoot = fileparts(fileparts(fileparts(fileparts(revisionDir))));
resultsRoot = fullfile(projectRoot,'results');
baseline = fullfile(projectRoot,'MPC_DWA_Fusion');
casadiPath = fullfile(baseline,'third_party', ...
    'casadi-3.8.0-windows64-matlab2018b');
runnerPath = fullfile(scriptDir,'run_v12a_pooled_weight_development.m');
helperPath = fullfile(scriptDir,'recover_existing_pooled_episode.m');
outdir = fullfile(resultsRoot, ...
    'v12a_pooled_weight_development_inclusive_dev48_20261012');
episodesDir = fullfile(outdir,'episodes');
errorsDir = fullfile(outdir,'errors');
manifestPath = fullfile(outdir,'pooled_development_manifest.mat');
lockDir = fullfile(outdir,'.pooled_development_lock');

[manifest,source,cfg,jobs,episodeNames,episodeFileSHA256, ...
    episodeRouteSHA256,dependencyInventorySHA256] = preflight_archive( ...
    scriptPath,runnerPath,helperPath,scriptDir,revisionDir,projectRoot, ...
    baseline,casadiPath,outdir,episodesDir,errorsDir,manifestPath,lockDir);
expectedEpisodes = numel(jobs);
goalTolerance = double(manifest.goalTolerance_m);
provenance = manifest.provenance;
helperSHA256 = file_sha256(helperPath);
runnerSHA256 = file_sha256(runnerPath);
sourceManifestSHA256 = file_sha256(manifestPath);

% The recovery lock is acquired only after the complete read-only preflight.
assert(~isfolder(lockDir) && isempty(gcp('nocreate')), ...
    'Recovery requires no runner lock and a fresh MATLAB session.');
lockFile = java.io.File(lockDir);
assert(lockFile.mkdir(),'Could not acquire Stage-1 recovery lock: %s',lockDir);
lockCleanup = onCleanup(@() release_recovery_lock(lockDir)); %#ok<NASGU>
assert_no_existing_final_outputs(outdir);

pool = parpool('local',4);
poolCleanup = onCleanup(@() close_recovery_pool(pool)); %#ok<NASGU>
addAttachedFiles(pool,{helperPath});
pathCommand = sprintf('addpath(''%s'',''-begin'')', ...
    strrep(scriptDir,'''',''''''));
pctRunOnAll(pathCommand);
spmd
    [~,resolvedRecoveryHelper,resolvedRecoveryHelperSHA256] = ...
        recover_existing_pooled_episode('__worker_identity__', ...
        helperPath,helperSHA256);
end
workerPaths = strings(pool.NumWorkers,1);
workerHashes = strings(pool.NumWorkers,1);
for worker = 1:pool.NumWorkers
    workerPaths(worker) = string(resolvedRecoveryHelper{worker});
    workerHashes(worker) = string(resolvedRecoveryHelperSHA256{worker});
end
assert(all(strcmpi(workerPaths,string(helperPath))) && ...
    all(strcmpi(workerHashes,string(helperSHA256))), ...
    'A parfor worker resolves a different recovery helper path or hash.');

workerRows = repmat(empty_episode_row(),expectedEpisodes,1);
workerFileSHA256 = strings(expectedEpisodes,1);
workerRouteSHA256 = strings(expectedEpisodes,1);
parfor i = 1:expectedEpisodes
    [workerRows(i),workerFileSHA256(i),workerRouteSHA256(i)] = ...
        recover_existing_pooled_episode( ...
        fullfile(episodesDir,char(episodeNames(i))),jobs(i).jobKey, ...
        jobs(i).candidateIndex,jobs(i).candidateKey,jobs(i).methodKey, ...
        jobs(i).methodLabel,jobs(i).sceneIndex,jobs(i).scenarioSeed, ...
        jobs(i).samplingSeed,goalTolerance,manifest.provenanceSignature, ...
        provenance,source.scenarios(jobs(i).sceneIndex),cfg, ...
        helperPath,helperSHA256);
end
assert(isequal(workerFileSHA256,episodeFileSHA256) && ...
    isequal(workerRouteSHA256,episodeRouteSHA256), ...
    'A checkpoint changed after pre-pool validation.');
assert_exact_row_coverage(workerRows,string(manifest.candidateKeys(:)'), ...
    string(manifest.methodKeys(:)'),double(manifest.sceneCount), ...
    double(manifest.samplingSeeds(:)'));

pooledTable = sortrows(struct2table(workerRows), ...
    {'CandidateIndex','MethodKey','SceneIndex','SamplingSeed'});
[methodSummary,candidateSummary,selection,classificationAudit] = ...
    score_candidates(pooledTable,string(manifest.candidateKeys(:)'), ...
    string(manifest.candidateLabels(:)'),double(manifest.candidateWeights), ...
    string(manifest.methodKeys(:)'),double(manifest.sceneCount), ...
    double(manifest.samplingSeeds(:)'));

episodeInventory = table(episodeNames,episodeFileSHA256, ...
    episodeRouteSHA256,'VariableNames', ...
    {'FileName','MAT_SHA256','RouteData_SHA256'});
episodeInventory = sortrows(episodeInventory,'FileName');
episodeInventorySHA256 = episode_inventory_sha256(episodeInventory);
manifest.status = "complete";
manifest.completedUTC = string(datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd''T''HH:mm:ssXXX'));
manifest.episodeRecordCount = expectedEpisodes;
manifest.unresolvedFailureCount = 0;
manifest.episodeInventory = episodeInventory;
manifest.episodeInventorySHA256 = episodeInventorySHA256;
save_mat_atomic(fullfile(outdir,'pooled_development_manifest.mat'), ...
    struct('manifest',manifest));
manifestSHA256 = file_sha256(fullfile(outdir, ...
    'pooled_development_manifest.mat'));
write_text_atomic(string(manifestSHA256)+ ...
    "  pooled_development_manifest.mat"+newline, ...
    fullfile(outdir,'pooled_development_manifest.sha256'));
selection.provenanceSignature = string(manifest.provenanceSignature);
selection.provenance = provenance;
selection.goalTolerance_m = goalTolerance;
selection.episodeInventorySHA256 = episodeInventorySHA256;
selection.manifestSHA256 = string(manifestSHA256);
selection.scoringRule = manifest.primaryScoreRule;
selection.tieBreakRule = manifest.tieBreakRule;
selection.endpointReclassification = classificationAudit;

recoveryManifest = struct( ...
    'status',"complete", ...
    'recoveryMode',"load_validate_existing_checkpoint_then_aggregate", ...
    'recoveredUTC',string(datetime('now','TimeZone','UTC', ...
        'Format','yyyy-MM-dd''T''HH:mm:ssXXX')), ...
    'sourceManifestPath',string(manifestPath), ...
    'sourceManifestSHA256',string(sourceManifestSHA256), ...
    'finalManifestSHA256',string(manifestSHA256), ...
    'provenance',provenance, ...
    'provenanceSignature',string(manifest.provenanceSignature), ...
    'runtimeDependencyInventorySHA256',string(dependencyInventorySHA256), ...
    'recoveryEntryPath',string(scriptPath), ...
    'recoveryEntrySHA256',string(file_sha256(scriptPath)), ...
    'recoveryWorkerPath',string(helperPath), ...
    'recoveryWorkerSHA256',string(helperSHA256), ...
    'originalRunnerPath',string(runnerPath), ...
    'originalRunnerSHA256',string(runnerSHA256), ...
    'workerPaths',workerPaths,'workerHelperSHA256',workerHashes, ...
    'episodeRecordCount',expectedEpisodes, ...
    'newEpisodeRecordCount',0,'newEpisodeRecordsCreated',false, ...
    'episodeInventory',episodeInventory, ...
    'episodeInventorySHA256',episodeInventorySHA256, ...
    'unresolvedFailureCount',0, ...
    'candidateKeys',string(manifest.candidateKeys(:)'), ...
    'candidateLabels',string(manifest.candidateLabels(:)'), ...
    'candidateWeights',double(manifest.candidateWeights), ...
    'methodKeys',string(manifest.methodKeys(:)'), ...
    'methodLabels',string(manifest.methodLabels(:)'), ...
    'sceneCount',double(manifest.sceneCount), ...
    'samplingSeeds',double(manifest.samplingSeeds(:)'), ...
    'goalTolerance_m',goalTolerance, ...
    'primaryScoreRule',manifest.primaryScoreRule, ...
    'tieBreakRule',manifest.tieBreakRule);

% No final output is written until all 4,320 worker loads revalidate.
write_table_atomic(episodeInventory,fullfile(outdir,'pooled_episode_sha256.csv'));
write_table_atomic(pooledTable,fullfile(outdir,'pooled_development_raw.csv'));
write_table_atomic(methodSummary,fullfile(outdir, ...
    'pooled_candidate_method_scores.csv'));
write_table_atomic(candidateSummary,fullfile(outdir, ...
    'pooled_candidate_scores.csv'));
write_table_atomic(classificationAudit,fullfile(outdir, ...
    'pooled_endpoint_reclassification.csv'));
save_mat_atomic(fullfile(outdir,'pooled_weight_selection.mat'), ...
    struct('selection',selection,'methodSummary',methodSummary, ...
    'candidateSummary',candidateSummary, ...
    'classificationAudit',classificationAudit,'provenance',provenance, ...
    'candidateWeights',double(manifest.candidateWeights), ...
    'candidateKeys',string(manifest.candidateKeys(:)')));
save_mat_atomic(fullfile(outdir,'pooled_development_bundle.mat'), ...
    struct('pooledTable',pooledTable,'methodSummary',methodSummary, ...
    'candidateSummary',candidateSummary, ...
    'classificationAudit',classificationAudit,'selection',selection, ...
    'provenance',provenance,'manifest',manifest, ...
    'candidateWeights',double(manifest.candidateWeights), ...
    'candidateKeys',string(manifest.candidateKeys(:)'), ...
    'methodKeys',string(manifest.methodKeys(:)'), ...
    'methodLabels',string(manifest.methodLabels(:)')));

write_text_atomic(string(file_sha256(fullfile(outdir, ...
    'pooled_episode_sha256.csv')))+ ...
    "  pooled_episode_sha256.csv"+newline, ...
    fullfile(outdir,'pooled_episode_sha256.csv.sha256'));
recoveryManifest.outputArtifactNames = [ ...
    "pooled_development_manifest.mat"; ...
    "pooled_development_raw.csv"; ...
    "pooled_candidate_method_scores.csv"; ...
    "pooled_candidate_scores.csv"; ...
    "pooled_endpoint_reclassification.csv"; ...
    "pooled_episode_sha256.csv"; ...
    "pooled_weight_selection.mat"; ...
    "pooled_development_bundle.mat"];
outputHashes = strings(numel(recoveryManifest.outputArtifactNames),1);
for i = 1:numel(outputHashes)
    outputHashes(i) = string(file_sha256(fullfile(outdir, ...
        char(recoveryManifest.outputArtifactNames(i)))));
end
recoveryManifest.outputArtifactSHA256 = outputHashes;
recoveryManifest.outputArtifactInventorySHA256 = sha256_text( ...
    strjoin(recoveryManifest.outputArtifactNames+":"+outputHashes,"|"));
save_mat_atomic(fullfile(outdir,'pooled_development_recovery_manifest.mat'), ...
    struct('recoveryManifest',recoveryManifest));
recoveryManifestSHA256 = file_sha256(fullfile(outdir, ...
    'pooled_development_recovery_manifest.mat'));
write_text_atomic(string(recoveryManifestSHA256)+ ...
    "  pooled_development_recovery_manifest.mat"+newline, ...
    fullfile(outdir,'pooled_development_recovery_manifest.sha256'));
artifactNames = recoveryManifest.outputArtifactNames;
artifactHashes = outputHashes;
write_table_atomic(table(artifactNames,artifactHashes, ...
    'VariableNames',{'FileName','SHA256'}), ...
    fullfile(outdir,'pooled_calibration_artifact_sha256.csv'));
fprintf('Validated existing Stage-1 archive and aggregated %d records.\n', ...
    expectedEpisodes);
fprintf('No episode was simulated or added. Output: %s\n',outdir);
end

function [manifest,source,cfg,jobs,episodeNames,episodeFileSHA256, ...
    episodeRouteSHA256,inventorySHA256] = preflight_archive( ...
    scriptPath,runnerPath,helperPath,scriptDir,revisionDir,projectRoot, ...
    baseline,casadiPath,outdir,episodesDir,errorsDir,manifestPath,lockDir)
assert(isfile(scriptPath) && isfile(runnerPath) && isfile(helperPath) && ...
    isfolder(outdir) && isfolder(episodesDir) && isfolder(errorsDir) && ...
    isfile(manifestPath),'Recovery input paths are incomplete.');
assert(~isfolder(lockDir) && ...
    ~isfolder(fullfile(outdir,'.pooled_development_recovery_lock')), ...
    'A Stage-1 runner/recovery lock already exists.');
assert_no_existing_final_outputs(outdir);
rootEntries = dir(fullfile(outdir,'*'));
rootEntries = rootEntries(~ismember({rootEntries.name},{'.','..'}));
allowedRootEntries = {'episodes','errors','pooled_development_manifest.mat'};
assert(all(ismember({rootEntries.name},allowedRootEntries)) && ...
    numel(rootEntries)==numel(allowedRootEntries), ...
    'Stage-1 output root has unexpected files or directories.');
errorEntries = dir(fullfile(errorsDir,'*'));
errorEntries = errorEntries(~ismember({errorEntries.name},{'.','..'}));
assert(isempty(errorEntries),'The Stage-1 errors directory is not empty.');

loaded = load(manifestPath,'manifest');
assert(isfield(loaded,'manifest') && isstruct(loaded.manifest), ...
    'Manifest MAT does not contain a manifest struct.');
manifest = loaded.manifest;
required = {'status','provenance','provenanceSignature','candidateKeys', ...
    'candidateLabels','candidateWeights','methodKeys','methodLabels', ...
    'sceneCount','scenarioSeed','samplingSeeds','goalTolerance_m', ...
    'expectedFreshEpisodes','expectedPooledRows', ...
    'fullRerunNoHistoricalEpisodeReuse','workerCount','workerPathAudit', ...
    'workerPathAuditSHA256','primaryScoreRule','tieBreakRule'};
assert(all(isfield(manifest,required)),'Manifest schema is incomplete.');
provenance = manifest.provenance;
candidateKeys = string(manifest.candidateKeys(:)');
candidateLabels = string(manifest.candidateLabels(:)');
candidateWeights = double(manifest.candidateWeights);
methodKeys = string(manifest.methodKeys(:)');
methodLabels = string(manifest.methodLabels(:)');
seeds = double(manifest.samplingSeeds(:)');
sceneCount = double(manifest.sceneCount);
goalTolerance = double(manifest.goalTolerance_m);
expectedCandidateKeys = ["equal","safety","goal","tracking", ...
    "smoothness","existing_engineering"];
expectedWeights = [0.25 0.25 0.25 0.25; ...
    0.55 0.15 0.15 0.15;0.15 0.55 0.15 0.15; ...
    0.15 0.15 0.55 0.15;0.15 0.15 0.15 0.55; ...
    0.35 0.30 0.15 0.20];
expectedMethods = ["lstm","cv","lstm_mpc_cv_dwa", ...
    "cv_mpc_lstm_dwa","static"];
expectedMethodLabels = ["MPC-DWA (shared LSTM)", ...
    "Coupled MPC-DWA (CV)","MPC-DWA (LSTM to MPC only)", ...
    "MPC-DWA (LSTM to DWA only)", ...
    "Reconstructed MPC-DWA (latest-position hold in both layers)"];
assert(isequal(candidateKeys,expectedCandidateKeys) && ...
    isequal(candidateWeights,expectedWeights) && ...
    numel(candidateLabels)==6 && isequal(methodKeys,expectedMethods) && ...
    isequal(methodLabels,expectedMethodLabels) && sceneCount==48 && ...
    double(manifest.scenarioSeed)==20261006 && isequal(seeds,1:3) && ...
    numel(candidateKeys)*numel(methodKeys)*sceneCount*numel(seeds)==4320 && ...
    double(manifest.expectedFreshEpisodes)==4320 && ...
    double(manifest.expectedPooledRows)==4320 && ...
    logical(manifest.fullRerunNoHistoricalEpisodeReuse) && ...
    double(manifest.workerCount)==4 && isscalar(goalTolerance) && ...
    string(manifest.primaryScoreRule)== ...
        "mean_method(mean_scene(mean_seed(corrected_safe_goal_arrival)))" && ...
    string(manifest.correctedContactRule)=="SweptMinClearance_m <= 0" && ...
    string(manifest.correctedGoalRule)=="FinalDistance_m <= GoalTolerance_m" && ...
    string(manifest.executionMode)== ...
        "fresh local four-worker pool; worker paths verified" && ...
    isfinite(goalTolerance) && goalTolerance>0, ...
    'Manifest differs from the frozen 4,320-episode design.');
status = string(manifest.status);
assert(any(status==["running","complete"]), ...
    'Manifest status is neither running nor complete.');
if status=="complete"
    assert(all(isfield(manifest,{'episodeRecordCount', ...
        'unresolvedFailureCount','episodeInventory', ...
        'episodeInventorySHA256'})) && ...
        double(manifest.episodeRecordCount)==4320 && ...
        double(manifest.unresolvedFailureCount)==0, ...
        'Complete manifest does not certify all 4,320 episodes.');
end

data = verify_frozen_inputs(provenance,scriptDir,revisionDir,projectRoot, ...
    baseline,casadiPath);
signature = provenance_signature(provenance,candidateKeys,candidateLabels, ...
    candidateWeights,methodKeys,goalTolerance,seeds);
assert(strcmpi(signature,char(manifest.provenanceSignature)), ...
    'Manifest provenance signature does not reproduce.');
verify_saved_worker_audit(manifest.workerPathAudit, ...
    provenance.WorkerPathAuditSHA256,manifest.workerPathAuditSHA256);

source = load(char(provenance.SourceBundlePath), ...
    'cfg','scenarios','seeds','scenarioSeed','modelSHA');
assert(all(isfield(source,{'cfg','scenarios','seeds','scenarioSeed','modelSHA'})) && ...
    numel(source.scenarios)==48 && isequal(double(source.seeds(:)'),1:3) && ...
    double(source.scenarioSeed)==20261006 && ...
    strcmpi(char(source.modelSHA),char(provenance.ModelSHA256)), ...
    'Frozen scene bundle does not match the saved Stage-1 design/model.');
tune = load(char(provenance.OriginalTuneBundlePath), ...
    'sourceSHA','modelPath','modelSHA','protocolSHA','candidateKeys', ...
    'candidateWeights','candidateLabels');
assert(all(isfield(tune,{'sourceSHA','modelPath','modelSHA','protocolSHA', ...
    'candidateKeys','candidateWeights','candidateLabels'})) && ...
    strcmpi(char(tune.sourceSHA),char(provenance.SourceBundleSHA256)) && ...
    strcmpi(char(tune.protocolSHA),char(provenance.ProtocolSHA256)) && ...
    strcmpi(char(tune.modelSHA),char(provenance.ModelSHA256)) && ...
    strcmpi(char(tune.modelPath),char(provenance.ModelPath)) && ...
    isequal(string(tune.candidateKeys(:)'),candidateKeys) && ...
    isequal(double(tune.candidateWeights),candidateWeights) && ...
    isequal(string(tune.candidateLabels(:)'),candidateLabels), ...
    'Frozen tune bundle differs from the saved Stage-1 design.');
model = load(char(provenance.ModelPath),'muX','sigX','muY','sigY');
assert(all(isfield(model,{'muX','sigX','muY','sigY'})), ...
    'Frozen model is missing normalization fields.');
cfg = source.cfg;
cfg.dyn.muX = model.muX;
cfg.dyn.sigX = model.sigX;
cfg.dyn.muY = model.muY;
cfg.dyn.sigY = model.sigY;
cfg.predictTime = 3.0;
cfg.mpc.N = 30;
cfg.dyn.N_pred = 30;
cfg.dyn.injectHorizon = 30;
cfg.dyn.dt = cfg.dt;
assert(strcmpi(sha256_text(jsonencode(source.cfg)), ...
    char(provenance.LoadedSourceConfigSHA256)) && ...
    strcmpi(sha256_text(jsonencode(cfg)), ...
    char(provenance.EffectiveBaseConfigSHA256)) && ...
    close_enough(double(cfg.goalTolerance),goalTolerance), ...
    'Source/effective config hashes do not reproduce.');

jobs = make_expected_jobs(candidateKeys,methodKeys,sceneCount,seeds, ...
    source.scenarios);
episodeNames = strings(4320,1);
for i = 1:4320, episodeNames(i) = jobs(i).jobKey+".mat"; end
entries = dir(fullfile(episodesDir,'*'));
entries = entries(~ismember({entries.name},{'.','..'}));
assert(numel(entries)==4320 && all(~[entries.isdir]) && ...
    all(endsWith(string({entries.name}),'.mat')), ...
    'Episode directory contains missing, extra, or non-MAT records.');
actualNames = sort(string({entries.name})');
assert(isequal(actualNames,sort(episodeNames)) && ...
    numel(unique(episodeNames))==4320, ...
    'Checkpoint filenames do not exactly cover the frozen 4,320 keys.');

rows = repmat(empty_episode_row(),4320,1);
episodeFileSHA256 = strings(4320,1);
episodeRouteSHA256 = strings(4320,1);
workerHelperPath = fullfile(fileparts(scriptPath), ...
    'recover_existing_pooled_episode.m');
workerHelperSHA256 = file_sha256(workerHelperPath);
for i = 1:4320
    job = jobs(i);
    [rows(i),episodeFileSHA256(i),episodeRouteSHA256(i)] = ...
        recover_existing_pooled_episode( ...
        fullfile(episodesDir,char(episodeNames(i))),job.jobKey, ...
        job.candidateIndex,job.candidateKey,job.methodKey,job.methodLabel, ...
        job.sceneIndex,job.scenarioSeed,job.samplingSeed,goalTolerance, ...
        manifest.provenanceSignature,provenance, ...
        source.scenarios(job.sceneIndex),cfg,workerHelperPath, ...
        workerHelperSHA256);
end
assert_exact_row_coverage(rows,candidateKeys,methodKeys,sceneCount,seeds);
verify_episode_inventory(manifest,episodeNames,episodeFileSHA256, ...
    episodeRouteSHA256);
assert_no_existing_final_outputs(outdir);
inventorySHA256 = data.runtimeDependencyInventorySHA256;
end

function data = verify_frozen_inputs(provenance,scriptDir,revisionDir, ...
    projectRoot,baseline,casadiPath)
required = {'OriginalRunnerPath','OriginalRunnerSHA256', ...
    'SupplementalRunnerPath','SupplementalRunnerSHA256', ...
    'OriginalCodeSHA256','RuntimeDependencyInventory', ...
    'RuntimeDependencyInventorySHA256','SimulatorSHA256', ...
    'TrustFunctionSHA256','StandaloneSimulatorSHA256','ConfigSHA256', ...
    'ConfigFilePath','ConfigFileSHA256','LoadedSourceConfigSHA256', ...
    'EffectiveBaseConfigSHA256','ModelPath','ModelSHA256', ...
    'SourceBundlePath','SourceBundleSHA256','SourceRawCSVPath', ...
    'SourceRawCSV_SHA256','ScenarioManifestPath','ScenarioManifestSHA256', ...
    'OriginalTuneBundlePath','OriginalTuneBundleSHA256','ProtocolPath', ...
    'ProtocolSHA256','ProtocolOverlayPath','ProtocolOverlaySHA256', ...
    'PooledProtocolPath','PooledProtocolSHA256','AmendmentPath', ...
    'AmendmentSHA256','WorkerPathAuditSHA256','CasadiFolder', ...
    'CasadiTreeSHA256','CombinedInputDataSHA256'};
assert(all(isfield(provenance,required)), ...
    'Saved provenance lacks required paths or hashes.');
expected = { ...
    'SupplementalRunnerPath',fullfile(scriptDir, ...
        'run_v12a_pooled_weight_development.m'); ...
    'OriginalRunnerPath',fullfile(scriptDir,'simulate_dynamic_v12a_timed.m'); ...
    'ConfigFilePath',fullfile(projectRoot,'config_LSTM.m'); ...
    'SourceBundlePath',fullfile(projectRoot,'results','confirmatory_revision', ...
        'confirmatory_48scenes_20261005_050804','experiment_bundle.mat'); ...
    'SourceRawCSVPath',fullfile(projectRoot,'results','confirmatory_revision', ...
        'confirmatory_48scenes_20261005_050804','confirmatory_raw.csv'); ...
    'ScenarioManifestPath',fullfile(projectRoot,'results','confirmatory_revision', ...
        'confirmatory_48scenes_20261005_050804','scenario_manifest.csv'); ...
    'OriginalTuneBundlePath',fullfile(projectRoot,'results', ...
        'v12_trust_weight_tuning_dev48_20261006','tuning_bundle.mat'); ...
    'ProtocolPath',fullfile(projectRoot,'paper','Conference_4Page_Submission', ...
        'versions','12_redesigned_submission','04_review', ...
        'redesigned_comparison_protocol.md'); ...
    'ProtocolOverlayPath',fullfile(revisionDir,'04_review', ...
        'redesigned_comparison_protocol.md'); ...
    'PooledProtocolPath',fullfile(revisionDir,'04_review', ...
        'pooled_weight_selection_protocol_v12a.md'); ...
    'AmendmentPath',fullfile(revisionDir,'04_review', ...
        'protocol_amendment_endpoint_inclusive_20261012.md'); ...
    'CasadiFolder',casadiPath};
for i = 1:size(expected,1)
    assert(strcmpi(char(string(provenance.(expected{i,1}))), ...
        char(string(expected{i,2}))), ...
        'Manifest path differs from the frozen location: %s',expected{i,1});
end
hashPairs = { ...
    'SupplementalRunnerPath','SupplementalRunnerSHA256'; ...
    'OriginalRunnerPath','OriginalRunnerSHA256'; ...
    'ConfigFilePath','ConfigFileSHA256'; ...
    'SourceBundlePath','SourceBundleSHA256'; ...
    'SourceRawCSVPath','SourceRawCSV_SHA256'; ...
    'ScenarioManifestPath','ScenarioManifestSHA256'; ...
    'OriginalTuneBundlePath','OriginalTuneBundleSHA256'; ...
    'ProtocolPath','ProtocolSHA256'; ...
    'ProtocolOverlayPath','ProtocolOverlaySHA256'; ...
    'PooledProtocolPath','PooledProtocolSHA256'; ...
    'AmendmentPath','AmendmentSHA256'};
for i = 1:size(hashPairs,1)
    path = char(provenance.(hashPairs{i,1}));
    assert(isfile(path) && strcmpi(file_sha256(path), ...
        char(provenance.(hashPairs{i,2}))), ...
        'Frozen input hash differs: %s',path);
end
assert(isfile(char(provenance.ModelPath)) && ...
    strcmpi(file_sha256(char(provenance.ModelPath)), ...
        char(provenance.ModelSHA256)) && ...
    strcmpi(file_sha256(fullfile(projectRoot,'computeTrust_dynamic.m')), ...
        char(provenance.TrustFunctionSHA256)) && ...
    strcmpi(file_sha256(fullfile(scriptDir, ...
        'simulate_standalone_controller_v12a_timed.m')), ...
        char(provenance.StandaloneSimulatorSHA256)) && ...
    strcmpi(file_sha256(char(provenance.ConfigFilePath)), ...
        char(provenance.ConfigSHA256)) && ...
    strcmpi(file_sha256(char(provenance.OriginalRunnerPath)), ...
        char(provenance.SimulatorSHA256)), ...
    'A recorded model/config/runtime dependency hash differs.');
assert(strcmpi(directory_sha256(casadiPath), ...
    char(provenance.CasadiTreeSHA256)), ...
    'CasADi recursive dependency hash differs.');
[inventory,inventorySHA256] = runtime_dependency_inventory( ...
    scriptDir,projectRoot,baseline,casadiPath);
assert(strcmp(char(inventory),char(provenance.RuntimeDependencyInventory)) && ...
