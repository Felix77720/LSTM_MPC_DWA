function value = directory_sha256(folder)
files=dir(fullfile(folder,'**','*'));
files=files(~[files.isdir]);
assert(~isempty(files),'Dependency folder contains no files: %s',folder);
paths=strings(numel(files),1);
for i=1:numel(files), paths(i)=string(fullfile(files(i).folder,files(i).name)); end
[~,order]=sort(paths);
files=files(order);
parts=strings(numel(files),1);
for i=1:numel(files)
    path=fullfile(files(i).folder,files(i).name);
    relative=extractAfter(string(path),strlength(string(folder))+1);
    parts(i)=relative+":"+string(file_sha256(path));
end
value=sha256_text(char(strjoin(parts,'|')));
end

function value = file_sha256(path)
md=java.security.MessageDigest.getInstance('SHA-256');
fid=fopen(path,'rb');
assert(fid>=0,'Cannot open file for SHA-256: %s',path);
cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
while true
    bytes=fread(fid,1024*1024,'*uint8');
    if isempty(bytes), break; end
    md.update(bytes);
end
digest=typecast(md.digest(),'uint8');
value=lower(reshape(dec2hex(digest)',1,[]));
end

function value = sha256_text(text)
md=java.security.MessageDigest.getInstance('SHA-256');
md.update(uint8(char(text)));
digest=typecast(md.digest(),'uint8');
value=lower(reshape(dec2hex(digest)',1,[]));
end

function tf = exact_frozen_status(text)
matches=regexp(char(text), ...
    '(?m)^[ \t]*(?:\*\*)?Status:[ \t]*([^\r\n]*)$','tokens');
if numel(matches)~=1, tf=false; return; end
status=string(regexprep(strtrim(matches{1}{1}),'\*\*[ \t]*$',''));
tf=status=="frozen";
end

function value = close_enough(a,b)
if isnan(double(a)) || isnan(double(b))
    value=isnan(double(a)) && isnan(double(b));
elseif ~isfinite(double(a)) || ~isfinite(double(b))
    value=false;
else
    value=abs(double(a)-double(b))<=1e-12*max([1,abs(double(a)),abs(double(b))]);
end
end

