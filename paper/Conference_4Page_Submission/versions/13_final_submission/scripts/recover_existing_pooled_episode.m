function [row,fileSHA256,routeSHA256] = recover_existing_pooled_episode( ...
    episodePath,jobKey,candidateIndex,candidateKey,methodKey,methodLabel, ...
    sceneIndex,scenarioSeed,samplingSeed,goalTolerance,provenanceSignature, ...
    expectedProvenance,scenario,cfg,expectedHelperPath,expectedHelperSHA256)
%RECOVER_EXISTING_POOLED_EPISODE Load and validate one existing checkpoint.
% This worker has no simulator, retry, random-number, or checkpoint-write path.

resolvedPath = [mfilename('fullpath') '.m'];
if nargin==3 && strcmp(string(episodePath),"__worker_identity__")
    expectedPath = char(jobKey);
    expectedSHA256 = char(string(candidateIndex));
    resolvedSHA256 = file_sha256(resolvedPath);
    assert(strcmpi(resolvedPath,expectedPath) && ...
        strcmpi(resolvedSHA256,expectedSHA256), ...
        'Worker is not executing the expected guarded recovery helper.');
    row = struct('WorkerPath',string(resolvedPath), ...
        'WorkerSHA256',string(resolvedSHA256));
    fileSHA256 = string(resolvedPath);
    routeSHA256 = string(resolvedSHA256);
    return;
end
assert(strcmpi(resolvedPath,char(expectedHelperPath)) && ...
    strcmpi(file_sha256(resolvedPath),char(expectedHelperSHA256)), ...
    'Worker is not executing the expected guarded recovery helper.');
assert(isfile(episodePath),'Existing episode checkpoint is missing: %s',episodePath);
beforeSHA = file_sha256(episodePath);
saved = load(episodePath,'jobEnvelope');
afterSHA = file_sha256(episodePath);
assert(strcmpi(beforeSHA,afterSHA), ...
    'Episode checkpoint changed while it was being read: %s',episodePath);
fileSHA256 = afterSHA;
assert(isfield(saved,'jobEnvelope') && isstruct(saved.jobEnvelope), ...
    'Checkpoint MAT lacks a jobEnvelope struct: %s',episodePath);
envelope = saved.jobEnvelope;
requiredEnvelope = {'jobKey','status','provenanceSignature','provenance', ...
    'retryHistory','row','trajectory','timestamps_s','controls', ...
    'obstacleTracks','start_m','goal_m','terminalState','terminalReason', ...
    'failureType','routeDataSHA256'};
assert(all(isfield(envelope,requiredEnvelope)) && ...
    string(envelope.status)=="complete", ...
    'Checkpoint status is not complete or its payload is incomplete: %s', ...
    episodePath);
assert(string(envelope.jobKey)==string(jobKey) && ...
    strcmpi(char(envelope.provenanceSignature),char(provenanceSignature)) && ...
    isequaln(envelope.provenance,expectedProvenance), ...
    'Checkpoint key, provenance signature, or provenance differs: %s',episodePath);
[~,actualKey,actualExtension] = fileparts(episodePath);
assert(strcmpi(actualKey,char(jobKey)) && strcmpi(actualExtension,'.mat'), ...
    'Checkpoint filename does not match the expected key: %s',episodePath);

row = envelope.row;
requiredRow = {'CandidateIndex','CandidateKey','MethodKey','MethodLabel', ...
    'SceneIndex','ScenarioSeed','SamplingSeed','GoalTolerance_m', ...
    'FinalDistance_m','SweptMinClearance_m','OriginalGoalArrival', ...
    'OriginalSweptCollision','OriginalSafeGoalArrival','NativeGoalArrival', ...
    'NativeSweptCollision','NativeSafeGoalArrival','CorrectedGoalArrival', ...
    'CorrectedSweptCollision','CorrectedSafeGoalArrival','NativeSuccess', ...
    'PathLength_m','LegacyStepInclusiveTime_ms','FailureType', ...
    'TerminalReason','Steps','PathStateCount','RetryCount','RetryReasons'};
assert(isstruct(row) && all(isfield(row,requiredRow)), ...
    'Checkpoint row is missing required fields: %s',episodePath);
assert(double(row.CandidateIndex)==candidateIndex && ...
    string(row.CandidateKey)==string(candidateKey) && ...
    string(row.MethodKey)==string(methodKey) && ...
    string(row.MethodLabel)==string(methodLabel) && ...
    double(row.SceneIndex)==sceneIndex && ...
    double(row.ScenarioSeed)==scenarioSeed && ...
    double(row.SamplingSeed)==samplingSeed && ...
    close_enough(double(row.GoalTolerance_m),double(goalTolerance)), ...
    'Checkpoint row does not match the expected exact key: %s',episodePath);
assert(isstruct(envelope.retryHistory) && ...
    double(row.RetryCount)==numel(envelope.retryHistory), ...
    'Checkpoint retry metadata does not match its row: %s',episodePath);

trajectory = double(envelope.trajectory);
timestamps = double(envelope.timestamps_s(:));
controls = double(envelope.controls);
assert(ismatrix(trajectory) && size(trajectory,1)>=1 && ...
    size(trajectory,2)>=3 && size(trajectory,1)==double(row.PathStateCount) && ...
    size(trajectory,1)==double(row.Steps)+1 && ...
    numel(timestamps)==size(trajectory,1) && ...
    size(controls,1)==size(trajectory,1) && ...
    all(isfinite(trajectory),'all') && all(isfinite(timestamps)) && ...
    all(isfinite(controls),'all') && ...
    all(abs(timestamps(:)-(0:double(row.Steps))'*double(cfg.dt))<=1e-10), ...
    'Stored route, controls, or timestamps are incomplete or misaligned.');
assert(norm(trajectory(1,1:3)'-double(scenario.start(:)))<=1e-10 && ...
    isequaln(envelope.obstacleTracks,scenario.obstacles) && ...
    isequal(double(envelope.start_m(:)),double(scenario.start(:))) && ...
    isequal(double(envelope.goal_m(:)),double(scenario.goal(:))) && ...
    isequal(double(envelope.terminalState),trajectory(end,:)) && ...
    string(envelope.terminalReason)==string(row.TerminalReason) && ...
    string(envelope.failureType)==string(row.FailureType), ...
    'Checkpoint route metadata differs from its fixed scene or row.');
finalDistance = norm(trajectory(end,1:3)'-double(scenario.goal(:)));
recomputedPathLength = sum(sqrt(sum(diff(trajectory(:,1:3),1,1).^2,2)));
recomputedSweptMinClearance = swept_min_clearance(trajectory, ...
    scenario.obstacles,double(cfg.UAV_radius));
assert(isfinite(finalDistance) && ...
    close_enough(finalDistance,double(row.FinalDistance_m)) && ...
    close_enough(recomputedPathLength,double(row.PathLength_m)) && ...
    close_enough(recomputedSweptMinClearance, ...
        double(row.SweptMinClearance_m)) && ...
    all(isfinite([row.FinalDistance_m,row.SweptMinClearance_m, ...
        row.GoalTolerance_m,row.PathLength_m])) && ...
    row.PathLength_m>=0 && ...
    (isnan(double(row.LegacyStepInclusiveTime_ms)) && row.Steps==0 || ...
        isfinite(double(row.LegacyStepInclusiveTime_ms)) && ...
        row.LegacyStepInclusiveTime_ms>=0) && ...
    strlength(string(row.FailureType))>0 && ...
    strlength(string(row.TerminalReason))>0, ...
    'Checkpoint row contains invalid terminal values or metrics.');
logicalFields = {'OriginalGoalArrival','OriginalSweptCollision', ...
    'OriginalSafeGoalArrival','NativeGoalArrival','NativeSweptCollision', ...
    'NativeSafeGoalArrival','CorrectedGoalArrival','CorrectedSweptCollision', ...
    'CorrectedSafeGoalArrival','NativeSuccess'};
for i = 1:numel(logicalFields)
    flag = double(row.(logicalFields{i}));
    assert(isscalar(flag) && isfinite(flag) && any(flag==[0 1]), ...
        'Checkpoint row has an invalid flag: %s',logicalFields{i});
end
nativeGoal = finalDistance<double(goalTolerance);
correctedGoal = finalDistance<=double(goalTolerance);
nativeCollision = double(row.SweptMinClearance_m)<0;
correctedCollision = double(row.SweptMinClearance_m)<=0;
assert(logical(row.OriginalGoalArrival)==nativeGoal && ...
    logical(row.NativeGoalArrival)==nativeGoal && ...
    logical(row.OriginalSweptCollision)==nativeCollision && ...
    logical(row.NativeSweptCollision)==nativeCollision && ...
    logical(row.OriginalSafeGoalArrival)==(nativeGoal && ~nativeCollision) && ...
    logical(row.NativeSafeGoalArrival)==(nativeGoal && ~nativeCollision) && ...
    logical(row.CorrectedGoalArrival)==correctedGoal && ...
    logical(row.CorrectedSweptCollision)==correctedCollision && ...
    logical(row.CorrectedSafeGoalArrival)== ...
        (correctedGoal && ~correctedCollision), ...
    'Checkpoint classification flags do not match stored measurements.');
routeSHA256 = episode_data_sha256(trajectory,timestamps,controls, ...
    scenario.obstacles);
assert(strcmpi(char(envelope.routeDataSHA256),routeSHA256), ...
    'Stored route payload hash does not reproduce: %s',episodePath);
end

function minGap = swept_min_clearance(trajectory,obstacles,uavRadius)
assert(isscalar(uavRadius) && isfinite(uavRadius) && uavRadius>=0 && ...
    ~isempty(obstacles),'Invalid fixed-scene clearance inputs.');
minGap=inf;
nIntervals=max(1,size(trajectory,1)-1);
for k=1:nIntervals
    if size(trajectory,1)==1, kRight=1; else, kRight=k+1; end
    for j=1:numel(obstacles)
        obstacleTrajectory=double(obstacles(j).traj);
        assert(size(obstacleTrajectory,1)>=kRight && ...
            size(obstacleTrajectory,2)>=3 && ...
            all(isfinite(obstacleTrajectory(k:kRight,1:3)),'all'), ...
            'Fixed obstacle track is too short/nonfinite for route validation.');
        relStart=trajectory(k,1:3)'-obstacleTrajectory(k,1:3)';
        relEnd=trajectory(kRight,1:3)'-obstacleTrajectory(kRight,1:3)';
        delta=relEnd-relStart;
        denominator=dot(delta,delta);
        if denominator>0
            alpha=max(0,min(1,-dot(relStart,delta)/denominator));
        else
            alpha=0;
        end
        gap=norm(relStart+alpha*delta)-double(obstacles(j).radius)-uavRadius;
        assert(isfinite(gap),'Nonfinite route clearance encountered.');
        minGap=min(minGap,gap);
    end
end
assert(isfinite(minGap),'Route swept clearance could not be reproduced.');
end

function value = episode_data_sha256(trajectory,timestamps,controls,obstacles)
md=java.security.MessageDigest.getInstance('SHA-256');
md.update(typecast(double(trajectory(:)),'uint8'));
md.update(typecast(double(timestamps(:)),'uint8'));
md.update(typecast(double(controls(:)),'uint8'));
for i=1:numel(obstacles)
    md.update(typecast(double(obstacles(i).traj(:)),'uint8'));
    md.update(typecast(double(obstacles(i).radius),'uint8'));
end
digest=typecast(md.digest(),'uint8');
value=lower(reshape(dec2hex(digest)',1,[]));
end

function value = file_sha256(path)
md=java.security.MessageDigest.getInstance('SHA-256');
fid=fopen(path,'rb');
assert(fid>=0,'Cannot open file for SHA-256: %s',path);
cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
while true
    bytes=fread(fid,1024*1024,'*uint8');
    if isempty(bytes), break; end
    md.update(bytes);
end
digest=typecast(md.digest(),'uint8');
value=lower(reshape(dec2hex(digest)',1,[]));
end

function tf = close_enough(a,b)
if isnan(double(a)) || isnan(double(b))
    tf=isnan(double(a)) && isnan(double(b));
elseif ~isfinite(double(a)) || ~isfinite(double(b))
    tf=false;
else
    tf=abs(double(a)-double(b))<=1e-12*max([1,abs(double(a)),abs(double(b))]);
end
end
