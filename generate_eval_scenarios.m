function scenarios = generate_eval_scenarios(cfg)
% generate_eval_scenarios - Build four evaluation scenarios with increasing
% obstacle count, obstacle radius, speed, and nonlinearity.

T  = cfg.dyn.T_obs;
dt = cfg.dyn.dt;

empty = struct('traj', {}, 'radius', {});
scenarios = repmat(struct('name', [], 'start', [], 'goal', [], 'obstacles', empty), 4, 1);

start = [1, 1, 1]';
goal  = [18, 18, 8]';

psi_nw = 3 * pi / 4;
psi_se = -pi / 4;

%% S1: two crossing obstacles, mild corridor compression
scenarios(1).name  = 'S1 双障碍轻度交叉';
scenarios(1).start = start;
scenarios(1).goal  = goal;
s = side_start(6.70, 4.2, 1);
scenarios(1).obstacles(1) = mk('accel', ...
    struct('x0', s(1), 'y0', s(2), 'z0', 3.3, 'psi0', psi_nw, 'v', 1.1, ...
           'a', 0.15, 'vmin', 0.4, 'vmax', 1.8, 'omega', 0.10, 'vz', 0), ...
    101, 1.2, T, dt);
s = side_start(11.59, 7.8, -1);
scenarios(1).obstacles(2) = mk('sine_speed', ...
    struct('x0', s(1), 'y0', s(2), 'z0', 5.4, 'psi0', psi_se, 'v', 1.3, ...
           'vamp', 0.30, 'vfreq', 0.40, 'omega', -0.10, 'vz', 0), ...
    102, 1.2, T, dt);

%% S2: four crossing obstacles, two on each side
scenarios(2).name  = 'S2 四障碍走廊交错';
scenarios(2).start = start;
scenarios(2).goal  = goal;
s = side_start(5.34, 3.0, 1);
scenarios(2).obstacles(1) = mk('straight', ...
    struct('x0', s(1), 'y0', s(2), 'z0', 2.8, 'psi0', psi_nw, 'v', 1.4, 'vz', 0), ...
    111, 1.5, T, dt);
s = side_start(7.79, 4.0, -1);
scenarios(2).obstacles(2) = mk('sine_speed', ...
    struct('x0', s(1), 'y0', s(2), 'z0', 3.8, 'psi0', psi_se, 'v', 1.2, ...
           'vamp', 0.30, 'vfreq', 0.45, 'omega', -0.12, 'vz', 0), ...
    112, 1.5, T, dt);
s = side_start(10.37, 5.5, 1);
scenarios(2).obstacles(3) = mk('turn', ...
    struct('x0', s(1), 'y0', s(2), 'z0', 4.9, 'psi0', psi_nw, 'v', 1.3, ...
           'omega', 0.18, 'vz', 0), ...
    113, 1.5, T, dt);
s = side_start(13.09, 6.5, -1);
scenarios(2).obstacles(4) = mk('accel', ...
    struct('x0', s(1), 'y0', s(2), 'z0', 6.0, 'psi0', psi_se, 'v', 0.8, ...
           'a', 0.15, 'vmin', 0.4, 'vmax', 2.0, 'omega', -0.15, 'vz', 0), ...
    114, 1.5, T, dt);

%% S3: five nonlinear obstacles that compress the corridor
scenarios(3).name  = 'S3 五障碍非线性走廊压缩';
scenarios(3).start = start;
scenarios(3).goal  = goal;
% Synchronize the crossing times with the ego vehicle.  The previous
% distances (2.2--5.4 m) made the obstacles cross the route several seconds
% before the ego reached the same along-track locations, so the 2-D plot
% looked interactive while the closed-loop run was mostly non-interacting.
% The reference speed is the observed early closed-loop cruise speed on the
% fixed evaluation route, not a claim about the maximum vehicle speed.
s3_route_speed_ref = 1.10;
t1 = (4.94 - 1) * sqrt(2) / s3_route_speed_ref;
t2 = (7.25 - 1) * sqrt(2) / s3_route_speed_ref + 1.2;
t3 = (8.74 - 1) * sqrt(2) / s3_route_speed_ref + 1.5;
t5 = (13.09 - 1) * sqrt(2) / s3_route_speed_ref + 1.8;
s = side_start(4.94, 0.8 * t1, 1);
scenarios(3).obstacles(1) = mk('straight', ...
    struct('x0', s(1), 'y0', s(2), 'z0', 2.6, 'psi0', psi_nw, 'v', 0.8, 'vz', 0), ...
    121, 1.8, T, dt);
s = side_start(7.25, 0.8 * t2, -1);
scenarios(3).obstacles(2) = mk('sine_speed', ...
    struct('x0', s(1), 'y0', s(2), 'z0', 3.6, 'psi0', psi_se, 'v', 0.8, ...
           'vamp', 0.35, 'vfreq', 0.50, 'omega', 0.0, 'vz', 0), ...
    122, 1.8, T, dt);
s = side_start(8.74, 0.8 * max(0, t3 - 1.0), 1);
scenarios(3).obstacles(3) = mk('hover_go', ...
    struct('x0', s(1), 'y0', s(2), 'z0', 4.2, 'psi0', psi_nw, 'v', 0.8, ...
           'T_hover', 1.0, 'omega', 0.0, 'vz', 0), ...
    123, 1.8, T, dt);
scenarios(3).obstacles(4) = mk('waypoints', ...
    struct('x0', 7.51, 'y0', 14.59, 'z0', 5.1, 'psi0', psi_se, 'v', 1.3, ...
           'waypoints', [7.5 14.6 5.1; 9.2 12.6 5.3; 10.5 9.5 5.5; 13.2 8.5 6.0], ...
           'wp_tol', 0.8, 'Kp_psi', 1.6, 'om_max', 1.2, ...
           'Kp_z', 0.8, 'vz_max', 0.5), ...
    124, 1.8, T, dt);
s = side_start(13.09, 0.5 * t5, 1);
scenarios(3).obstacles(5) = mk('zigzag', ...
    struct('x0', s(1), 'y0', s(2), 'z0', 6.0, 'psi0', psi_nw, 'v', 0.5, ...
           'omega_amp', 0.60, 'freq', 0.40, 'vz', 0), ...
    125, 1.8, T, dt);

%% S4: six obstacles, dense corridor compression with overlapping maneuvers
scenarios(4).name  = 'S4 六障碍密集走廊压缩';
scenarios(4).start = start;
scenarios(4).goal  = goal;
s = side_start(4.26, 1.8, 1);
scenarios(4).obstacles(1) = mk('zigzag', ...
    struct('x0', s(1), 'y0', s(2), 'z0', 2.3, 'psi0', psi_nw, 'v', 1.8, ...
           'omega_amp', 0.60, 'freq', 0.50, 'vz', 0), ...
    131, 2.0, T, dt);
s = side_start(6.02, 2.8, -1);
scenarios(4).obstacles(2) = mk('sine_speed', ...
    struct('x0', s(1), 'y0', s(2), 'z0', 3.1, 'psi0', psi_se, 'v', 1.6, ...
           'vamp', 0.35, 'vfreq', 0.50, 'omega', -0.12, 'vz', 0), ...
    132, 2.0, T, dt);
s = side_start(7.79, 4.2, 1);
scenarios(4).obstacles(3) = mk('accel', ...
    struct('x0', s(1), 'y0', s(2), 'z0', 3.8, 'psi0', psi_nw, 'v', 1.0, ...
           'a', 0.20, 'vmin', 0.4, 'vmax', 2.3, 'omega', 0.15, 'vz', 0), ...
    133, 2.0, T, dt);
scenarios(4).obstacles(4) = mk('waypoints', ...
    struct('x0', 6.30, 'y0', 12.80, 'z0', 4.5, 'psi0', psi_se, 'v', 1.4, ...
           'waypoints', [6.3 12.8 4.5; 8.2 11.0 4.7; 9.5 9.0 4.9; 11.5 8.0 5.4], ...
           'wp_tol', 0.8, 'Kp_psi', 1.6, 'om_max', 1.2, ...
           'Kp_z', 0.8, 'vz_max', 0.5), ...
    134, 2.0, T, dt);
s = side_start(11.32, 4.8, 1);
scenarios(4).obstacles(5) = mk('hover_go', ...
    struct('x0', s(1), 'y0', s(2), 'z0', 5.3, 'psi0', psi_nw, 'v', 1.7, ...
           'T_hover', 1.0, 'omega', 0.12, 'vz', 0), ...
    135, 2.0, T, dt);
s = side_start(13.09, 5.6, -1);
scenarios(4).obstacles(6) = mk('turn', ...
    struct('x0', s(1), 'y0', s(2), 'z0', 6.0, 'psi0', psi_se, 'v', 1.6, ...
           'omega', -0.20, 'vz', 0), ...
    136, 2.0, T, dt);
end

function s = side_start(c, d, dir)
% side_start - Place an obstacle on one side of the y=x diagonal so that it
% crosses the route near coordinate c after travelling d metres along heading.
u = d / sqrt(2);
if dir > 0
    s = [c + u, c - u];
else
    s = [c - u, c + u];
end
end

function o = mk(kind, p, seed, radius, T, dt)
% mk - Build one dynamic obstacle struct from a maneuver parameter struct.
o = struct('traj', generate_obstacle_trajectory(kind, p, T, dt, seed), ...
           'radius', radius);
end
